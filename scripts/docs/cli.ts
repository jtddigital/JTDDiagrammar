import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRegistry } from '@jtd/core';
import { examplesSection, exampleProblems, images, IMG_DIR, replaceSection } from './readme.ts';

const mode = process.argv[2];
if (mode !== 'build' && mode !== 'check') throw new Error('usage: cli.ts build|check');

const root = new URL('../../', import.meta.url);
const at = (p: string) => new URL(p, root);
const reg = createRegistry();
const problems = exampleProblems(reg);

const readme = readFileSync(at('README.md'), 'utf8');
const files = new Map([['README.md', replaceSection(readme, examplesSection(reg))], ...images(reg)]);
const existing = existsSync(at(IMG_DIR)) ? readdirSync(at(IMG_DIR)).map((f) => `${IMG_DIR}/${f}`) : [];
const stale = existing.filter((f) => !files.has(f));

if (mode === 'build') {
  mkdirSync(at(IMG_DIR), { recursive: true });
  for (const [path, content] of files) writeFileSync(at(path), content);
  for (const f of stale) rmSync(at(f));
} else {
  for (const [path, content] of files)
    if (!existsSync(at(path)) || readFileSync(at(path), 'utf8') !== content) problems.push(`${path} is stale: run \`pnpm docs:build\``);
  for (const f of stale) problems.push(`${f} is not generated by any example: run \`pnpm docs:build\``);
}

if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}
console.log(`docs ${mode}: ok (${files.size - 1} images)`);
