/**
 * Generates packages/core/src/measure/font-metrics.ts from Liberation Sans (SIL OFL 1.1),
 * which is metric-compatible with Arial (URS-LY-009). Usage: tsx scripts/fonts/metrics.ts [fontDir]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import opentype from 'opentype.js';

const dir = process.argv[2] ?? '/usr/share/fonts/truetype/liberation';
const FIRST = 32;
const LAST = 255;

const load = (file: string) => {
  const buf = readFileSync(`${dir}/${file}`);
  return opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
};
const widths = (font: ReturnType<typeof load>) =>
  Array.from({ length: LAST - FIRST + 1 }, (_, i) => font.charToGlyph(String.fromCodePoint(FIRST + i)).advanceWidth ?? 0);

const regular = load('LiberationSans-Regular.ttf');
const bold = load('LiberationSans-Bold.ttf');

const out = `// Generated by scripts/fonts/metrics.ts from Liberation Sans (SIL OFL 1.1). Do not edit.
// Advance widths in font units for code points ${FIRST}..${LAST}; Arial-compatible.
export const FONT = {
  family: "Arial, 'Liberation Sans', Helvetica, sans-serif",
  unitsPerEm: ${regular.unitsPerEm},
  ascender: ${regular.ascender},
  descender: ${-regular.descender},
  firstCode: ${FIRST},
  regular: [${widths(regular).join(', ')}],
  bold: [${widths(bold).join(', ')}],
} as const;
`;
writeFileSync(new URL('../../packages/core/src/measure/font-metrics.ts', import.meta.url), out);
console.log('font metrics written');
